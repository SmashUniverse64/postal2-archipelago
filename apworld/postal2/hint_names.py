def extra_scrounge_catalog() -> list[dict]:
    """NAMED_STASH_POS piles as SC_ catalog entries (no ID shift)."""
    existing = defaultdict(int)
    for e in SCROUNGE_CATALOG:
        existing[(e["map"], e["cls"])] += 1
    groups: dict[tuple[str, str], list] = defaultdict(list)
    for e in NAMED_STASH_POS:
        mk, cls = e["map"], e["cls"]
        if mk in _EXTRA_SKIP_MAPS or (mk, cls) in _EXTRA_SKIP_MAP_CLS:
            continue
        if cls == "CrackColaPickup":
            continue
        groups[(mk, cls)].append(e)
    out = []
    for (mk, cls), rows in sorted(groups.items(), key=lambda kv: (kv[0][0], kv[0][1])):
        rows = sorted(rows, key=lambda r: (r["x"], r["y"], r["z"]))
        start = existing[(mk, cls)]
        total = start + len(rows)
        label = ITEM_FROM_CLS.get(cls, cls.replace("Pickup", ""))
        prefix = MAP_PREFIX.get(mk, mk)
        for i, row in enumerate(rows, start=1):
            n = start + i
            unique = f"SC_{mk}_{cls}_{n:02d}"
            if total > 1:
                disp = f"{prefix} - {label} {n}"
            else:
                disp = f"{prefix} - {label}"
            out.append({
                "unique": unique,
                "name": disp,
                "map": mk,
                "cls": cls,
                "x": row["x"],
                "y": row["y"],
                "z": row["z"],
                "kind": "scrounge",
            })
    return out


