    r"^(?:Even More|Yet Another|The Last|Another|More|"
    r"(?:Twenty-|Thirty-)?(?:First|Second|Third|Fourth|Fifth|Sixth|Seventh|"
    r"Eighth|Ninth)|Tenth|Eleventh|Twelfth|Thirteenth|Fourteenth|Fifteenth|"
