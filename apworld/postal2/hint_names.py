_ITEM_TYPES = sorted(set(ITEM_FROM_CLS.values()), key=len, reverse=True)
_HEIGHT_WORDS = (
    "roof", "upper", "lower", "shelf", "desk", "floor", "catwalk",
    "basement", "lobby", "underpass", "undercarriage", "pit",
)


def _catalog_label(name: str) -> str:
    if " - " in name:
        return name.split(" - ", 1)[1]
    return name


def _item_from_entry(entry: dict) -> str:
    cls = entry.get("cls") or ""
    if cls in ITEM_FROM_CLS:
        return ITEM_FROM_CLS[cls]
    label = _catalog_label(entry.get("name") or "")
    for t in _ITEM_TYPES:
        if label == t or label.startswith(t + " "):
            return t
    parts = label.rsplit(" ", 1)
    if len(parts) == 2 and parts[1].isdigit():
        return parts[0]
    return label or cls.replace("Pickup", "")


def _place_from_hint(hint: str) -> str:
    rest = hint.strip()
    stripped = True
    while stripped and rest:
        stripped = False
        low = rest.lower()
        for t in _ITEM_TYPES:
            tl = t.lower()
            if low == tl:
                return ""
            if low.startswith(tl + " "):
                rest = rest[len(t) + 1:].strip()
                stripped = True
                break
            if tl.endswith("s") and low.startswith(tl[:-1] + " "):
                rest = rest[len(tl[:-1]) + 1:].strip()
                stripped = True
                break
    for prep in (
        "in the ", "on the ", "in ", "on ", "behind ",
        "underneath ", "under ", "at the ", "at ", "by the ", "by ",
        "inside ", "between ", "near ",
    ):
        if rest.lower().startswith(prep):
            return rest[len(prep):].strip()
    return rest.strip()


def _seed_dist(ax: float, ay: float, az: float, bx: float, by: float, bz: float) -> float:
    dx = ax - bx
    dy = ay - by
    dz = (az - bz) * 0.35
    return (dx * dx + dy * dy + dz * dz) ** 0.5


def _with_height(place: str, pile_z: float, seed_z: float) -> str:
    if not place:
        return place
    low = place.lower()
    if any(w in low for w in _HEIGHT_WORDS):
        return place
    if pile_z > seed_z + 280:
        return f"{place} Roof"
    if pile_z < seed_z - 420:
        return f"{place} Lower Level"
    return place


def _cola_unique(map_key: str, label: str) -> str | None:
    if not label.startswith("Crackola Machine "):
        return None
    num = label[len("Crackola Machine "):].strip()
    if not num.isdigit():
        return None
    return f"COLA_{map_key}_{int(num):02d}"


def _atm_unique(map_key: str, label: str) -> str | None:
    if label == "ATM":
        return f"ATM_{map_key}_1"
    if label.startswith("ATM "):
        rest = label[4:].strip()
        if rest.isdigit():
            return f"ATM_{map_key}_{int(rest)}"
    return None


def _stash_by_map_cls() -> dict[tuple[str, str], list]:
    by = defaultdict(list)
    for e in NAMED_STASH_POS:
        by[(e["map"], e["cls"])].append(e)
    return by


def resolve_hint_names() -> dict[str, str]:
    """unique -> full Archipelago location name."""
    by_map_label = {}
    for e in list(SCROUNGE_CATALOG) + list(EXTRA_SCROUNGE_CATALOG):
        by_map_label[(e["map"], _catalog_label(e["name"]))] = e

    out = {}
    used = set()
    for map_key, label, hint in HINT_LABELS:
        prefix = MAP_PREFIX.get(map_key, map_key)
        full = f"{prefix} - {hint}"
        entry = by_map_label.get((map_key, label))
        if entry is None:
            # Former named-cache maps skip that class from SCROUNGE_CATALOG, so
            # extra piles number from 1. Unnumbered HINT_LABELS keys still match.
            entry = by_map_label.get((map_key, f"{label} 1"))
        unique = entry["unique"] if entry else None
        if unique is None:
            unique = NAMED_BY_MAP_LABEL.get((map_key, label))
        if unique is None:
            unique = _atm_unique(map_key, label)
        if unique is None:
            unique = _cola_unique(map_key, label)
        if unique:
            out[unique] = full
            used.add(full)

    seeds: dict[str, list[tuple[float, float, float, str]]] = defaultdict(list)
    for map_key, x, y, z, place in PLACE_SEEDS:
        seeds[map_key].append((float(x), float(y), float(z), place))
    for map_key, label, hint in HINT_LABELS:
        entry = by_map_label.get((map_key, label))
        if not entry:
            continue
        place = _place_from_hint(hint)
        if place:
            seeds[map_key].append((entry["x"], entry["y"], entry["z"], place))
    stash = _stash_by_map_cls()
    for map_key, cls, idx, place in NAMED_PLACE_SEEDS:
        rows = stash.get((map_key, cls), [])
        if not rows:
            continue
        row = rows[idx] if idx < len(rows) else rows[0]
        seeds[map_key].append((row["x"], row["y"], row["z"], place))

    pending = []
    for e in list(SCROUNGE_CATALOG) + list(EXTRA_SCROUNGE_CATALOG):
        if e["map"] == "INTRO" or e["unique"] in out:
            continue
        pending.append(e)

    assigned: list[tuple[str, str]] = []
    for e in pending:
        mk = e["map"]
        options = seeds.get(mk)
        if not options:
            continue
        x, y, z = e["x"], e["y"], e["z"]
        best = options[0]
        best_d = _seed_dist(x, y, z, best[0], best[1], best[2])
        for s in options[1:]:
            d = _seed_dist(x, y, z, s[0], s[1], s[2])
            if d < best_d:
                best = s
                best_d = d
        place = _with_height(best[3], z, best[2])
        if not place:
            continue
        item = _item_from_entry(e)
        prefix = MAP_PREFIX.get(mk, mk)
        assigned.append((e["unique"], f"{prefix} - {item} {place}"))

    groups: dict[str, list[str]] = defaultdict(list)
    for unique, full in assigned:
        groups[full].append(unique)
    for full, uniques in groups.items():
        n = 2 if full in used else 1
        for unique in uniques:
            if n == 1:
                name = full
            else:
                name = f"{full} {n}"
            while name in used:
                n += 1
                name = f"{full} {n}"
            out[unique] = name
            used.add(name)
            n += 1
    return out


HINT_BY_UNIQUE = resolve_hint_names()


def unmatched_hints() -> list[tuple[str, str, str]]:
    found = set(HINT_BY_UNIQUE)
    missed = []
    for map_key, label, hint in HINT_LABELS:
        prefix = MAP_PREFIX.get(map_key, map_key)
        unique = None
        for e in list(SCROUNGE_CATALOG) + list(EXTRA_SCROUNGE_CATALOG):
            if e["map"] == map_key and _catalog_label(e["name"]) == label:
                unique = e["unique"]
                break
        if unique is None:
            for e in list(SCROUNGE_CATALOG) + list(EXTRA_SCROUNGE_CATALOG):
                if e["map"] == map_key and _catalog_label(e["name"]) == f"{label} 1":
                    unique = e["unique"]
                    break
        if unique is None:
            unique = NAMED_BY_MAP_LABEL.get((map_key, label))
        if unique is None:
            unique = _atm_unique(map_key, label) or _cola_unique(map_key, label)
        if unique not in found or unique is None:
            missed.append((map_key, label, hint))
    return missed


def apply_hint_names(locs: list, skip_uniques=None) -> None:
    skip = skip_uniques or set()
    for loc in locs:
        unique = loc.get("unique")
        if unique in skip:
            continue
        name = HINT_BY_UNIQUE.get(unique)
        if name:
            loc["name"] = name
